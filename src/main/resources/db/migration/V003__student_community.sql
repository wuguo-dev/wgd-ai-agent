CREATE TABLE public.community_category (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(80) NOT NULL UNIQUE CHECK (length(trim(name)) > 0),
 description VARCHAR(500) NOT NULL DEFAULT '',
 sort_order INTEGER NOT NULL DEFAULT 0 CHECK (sort_order BETWEEN 0 AND 10000),
 status VARCHAR(16) NOT NULL DEFAULT 'ENABLED' CHECK (status IN ('ENABLED','DISABLED')),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE public.community_question (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES public.community_users(id),
 category_id BIGINT NOT NULL REFERENCES public.community_category(id),
 title VARCHAR(200) NOT NULL CHECK (length(trim(title)) > 0),
 content TEXT NOT NULL CHECK (length(trim(content)) BETWEEN 1 AND 20000),
 status VARCHAR(16) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','APPROVED','REJECTED')),
 reject_reason VARCHAR(1000),
 reviewed_by BIGINT REFERENCES public.community_users(id),
 reviewed_at TIMESTAMP WITH TIME ZONE,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK ((status = 'PENDING' AND reviewed_by IS NULL AND reviewed_at IS NULL AND reject_reason IS NULL)
 OR (status = 'APPROVED' AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL AND reject_reason IS NULL)
 OR (status = 'REJECTED' AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL AND length(trim(reject_reason)) > 0))
);
CREATE TABLE public.community_answer (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 question_id BIGINT NOT NULL REFERENCES public.community_question(id),
 user_id BIGINT NOT NULL REFERENCES public.community_users(id),
 content TEXT NOT NULL CHECK (length(trim(content)) BETWEEN 1 AND 10000),
 status VARCHAR(16) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','APPROVED','REJECTED')),
 reject_reason VARCHAR(1000),
 reviewed_by BIGINT REFERENCES public.community_users(id),
 reviewed_at TIMESTAMP WITH TIME ZONE,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK ((status = 'PENDING' AND reviewed_by IS NULL AND reviewed_at IS NULL AND reject_reason IS NULL)
 OR (status = 'APPROVED' AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL AND reject_reason IS NULL)
 OR (status = 'REJECTED' AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL AND length(trim(reject_reason)) > 0))
);
CREATE TABLE public.community_favorite (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES public.community_users(id),
 question_id BIGINT NOT NULL REFERENCES public.community_question(id),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(user_id,question_id)
);
CREATE INDEX community_category_order ON public.community_category(sort_order,id);
CREATE INDEX community_question_public ON public.community_question(status,created_at DESC,id DESC);
CREATE INDEX community_question_category ON public.community_question(category_id,status,created_at DESC,id DESC);
CREATE INDEX community_question_owner ON public.community_question(user_id,created_at DESC,id DESC);
CREATE INDEX community_answer_public ON public.community_answer(question_id,status,created_at DESC,id DESC);
CREATE INDEX community_answer_owner ON public.community_answer(user_id,created_at DESC,id DESC);
CREATE INDEX community_answer_review ON public.community_answer(status,created_at DESC,id DESC);
CREATE INDEX community_favorite_question ON public.community_favorite(question_id);

