CREATE TABLE public.admin_operation_log (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 operator_id BIGINT NOT NULL REFERENCES public.community_users(id),
 action VARCHAR(32) NOT NULL CHECK (action IN ('QUESTION_APPROVE','QUESTION_REJECT','QUESTION_DELETE','QUESTION_RESTORE','ANSWER_APPROVE','ANSWER_REJECT','ANSWER_DELETE','ANSWER_RESTORE','USER_ENABLE','USER_DISABLE','CATEGORY_CREATE','CATEGORY_UPDATE','CATEGORY_ENABLE','CATEGORY_DISABLE')),
 target_type VARCHAR(16) NOT NULL CHECK (target_type IN ('QUESTION','ANSWER','USER','CATEGORY')),
 target_id BIGINT NOT NULL,
 reason VARCHAR(1000),
 before_state TEXT,
 after_state TEXT NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX admin_operation_log_created ON public.admin_operation_log(created_at DESC,id DESC);
